# 4. ENHANCED GREY WOLF OPTIMIZER
# =====================================================

def EGWO(population, iterations, lower, upper):

    wolves = population.copy()
    n = len(wolves)

    p = 0.4

    history = []
    evaluations = 0

    for t in range(iterations):

        power = np.array([fitness(x) for x in wolves])
        evaluations += n

        idx = np.argsort(power)[::-1]

        alpha = wolves[idx[0]]
        beta = wolves[idx[1]]
        delta = wolves[idx[2]]

        best_power = power[idx[0]]
        history.append(best_power)

        # Nonlinear convergence factor
        a = 2 * (1 - t / iterations) ** 2

        new_wolves = np.zeros(n)

        for i in range(n):

            r1 = np.random.rand(3)
            r2 = np.random.rand(3)

            A1 = 2 * a * r1[0] - a
            C1 = 2 * r2[0]

            A2 = 2 * a * r1[1] - a
            C2 = 2 * r2[1]

            A3 = 2 * a * r1[2] - a
            C3 = 2 * r2[2]

            D_alpha = abs(C1 * alpha - wolves[i])
            D_beta = abs(C2 * beta - wolves[i])
            D_delta = abs(C3 * delta - wolves[i])

            X1 = alpha - A1 * D_alpha
            X2 = beta - A2 * D_beta
            X3 = delta - A3 * D_delta

            # Weighted average position update
            X_new = (3 * X1 + 2 * X2 + X3) / 6

            # Pouncing behaviour
            if a < p:

                d = np.random.uniform(0, 5)
                direction = np.random.choice([-1, 1])

                X_new = alpha + direction * d

            new_wolves[i] = X_new

        wolves = np.clip(new_wolves, lower, upper)

    power = np.array([fitness(x) for x in wolves])
    evaluations += n

    best = np.argmax(power)
    history.append(power[best])

    return wolves[best], power[best], history, evaluations


