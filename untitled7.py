# 5. MAIN PROGRAM
# =====================================================

np.random.seed(42)

LOWER = 0
UPPER = 100

WOLVES = 5
ITERATIONS = 50

# Same initial population for fair comparison
initial_population = np.random.uniform(
    LOWER, UPPER, WOLVES
)

# Run OGWO
start = time.perf_counter()

ogwo_v, ogwo_p, ogwo_history, ogwo_eval = OGWO(
    initial_population,
    ITERATIONS,
    LOWER,
    UPPER
)

ogwo_time = time.perf_counter() - start

# Run EGWO with identical initial population
start = time.perf_counter()

egwo_v, egwo_p, egwo_history, egwo_eval = EGWO(
    initial_population,
    ITERATIONS,
    LOWER,
    UPPER
)

egwo_time = time.perf_counter() - start


# =====================================================
# 6. REFERENCE GLOBAL MAXIMUM
# =====================================================

voltage_grid = np.linspace(LOWER, UPPER, 100001)
power_grid = pv_power(voltage_grid)

global_index = np.argmax(power_grid)

global_voltage = voltage_grid[global_index]
global_power = power_grid[global_index]


# =====================================================
# 7. PERFORMANCE CALCULATION
# =====================================================

def tracking_efficiency(power):
    return (power / global_power) * 100


def convergence_iteration(history, target):
    for i, value in enumerate(history):
        if value >= target:
            return i
    return -1


target = 0.99 * global_power

results = pd.DataFrame({
    "Algorithm": ["OGWO", "EGWO"],
    "Best Voltage (V)": [ogwo_v, egwo_v],
    "Maximum Power (W)": [ogwo_p, egwo_p],
    "Tracking Efficiency (%)": [
        tracking_efficiency(ogwo_p),
        tracking_efficiency(egwo_p)
    ],
    "Convergence Iteration (99%)": [
        convergence_iteration(ogwo_history, target),
        convergence_iteration(egwo_history, target)
    ],
    "Execution Time (s)": [ogwo_time, egwo_time],
    "Fitness Evaluations": [ogwo_eval, egwo_eval]
})

