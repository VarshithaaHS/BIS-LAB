# =====================================================
# 1. SYNTHETIC PV MODEL UNDER PARTIAL SHADING
# =====================================================

def pv_power(voltage):
    """
    Synthetic multimodal P-V curve.
    Represents multiple peaks caused by partial shading.
    Replace with a validated PV model or measured data
    for real experimental validation.
    """

    peaks = [
        (18, 120, 5),
        (35, 210, 7),
        (55, 170, 6),
        (75, 135, 8)
    ]

    power = 0

    for center, amplitude, width in peaks:
        power += amplitude * np.exp(
            -((voltage - center) ** 2) / (2 * width ** 2)
        )

    return power


# =====================================================
# 2. FITNESS FUNCTION
# =====================================================

def fitness(voltage):
    return pv_power(voltage)


# =====================================================
# 3. ORIGINAL GREY WOLF OPTIMIZER
# =====================================================

def OGWO(population, iterations, lower, upper):

    wolves = population.copy()
    n = len(wolves)

    history = []
    evaluations = 0

    for t in range(iterations):

        power = np.array([fitness(x) for x in wolves])
        evaluations += n

        idx = np.argsort(power)[::-1]

        alpha = wolves[idx[0]]
        beta = wolves[idx[1]]
        delta = wolves[idx[2]]

        best_power = power[idx[0]]
        history.append(best_power)

        a = 2 - 2 * t / iterations

        new_wolves = np.zeros(n)

        for i in range(n):

            r1 = np.random.rand(3)
            r2 = np.random.rand(3)

            A1 = 2 * a * r1[0] - a
            C1 = 2 * r2[0]

            A2 = 2 * a * r1[1] - a
            C2 = 2 * r2[1]

            A3 = 2 * a * r1[2] - a
            C3 = 2 * r2[2]

            D_alpha = abs(C1 * alpha - wolves[i])
            D_beta = abs(C2 * beta - wolves[i])
            D_delta = abs(C3 * delta - wolves[i])

            X1 = alpha - A1 * D_alpha
            X2 = beta - A2 * D_beta
            X3 = delta - A3 * D_delta

            new_wolves[i] = (X1 + X2 + X3) / 3

        wolves = np.clip(new_wolves, lower, upper)

    power = np.array([fitness(x) for x in wolves])
    evaluations += n

    best = np.argmax(power)
    history.append(power[best])

    return wolves[best], power[best], history, evaluations


