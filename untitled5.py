import random
import math
from copy import deepcopy

# ============================================================
# CUCKOO SEARCH FOR NURSE SCHEDULING
# With evolutionary crossover, constraint repair, and
# rescheduling support
# ============================================================

# -------------------- PROBLEM DATA ---------------------------

NURSES = 8
DAYS = 7
SHIFTS = ["Morning", "Evening", "Night"]
NUM_SHIFTS = len(SHIFTS)

# Minimum nurses required per shift, for each day.
# Rows = days; columns = Morning, Evening, Night.
REQUIREMENTS = [
    [2, 2, 1],
    [2, 2, 1],
    [2, 2, 1],
    [2, 2, 1],
    [2, 2, 1],
    [2, 2, 1],
    [2, 2, 1],
]

# availability[nurse][day][shift]
# True = available; False = unavailable.
AVAILABILITY = [
    [[True] * NUM_SHIFTS for _ in range(DAYS)]
    for _ in range(NURSES)
]

# Example: Nurse 0 is unavailable for the night shift on day 2.
AVAILABILITY[0][2][2] = False

# Maximum consecutive working days.
MAX_CONSECUTIVE_DAYS = 5

# Maximum shifts assigned to each nurse during the week.
MAX_WEEKLY_SHIFTS = 5

# Cuckoo Search parameters
POPULATION_SIZE = 30
DISCOVERY_PROBABILITY = 0.25
MAX_ITERATIONS = 300

# Penalty weights
W_COVERAGE = 1000
W_AVAILABILITY = 1000
W_DAILY_ASSIGNMENT = 1000
W_REST = 1000
W_WEEKLY_LIMIT = 100
W_CONSECUTIVE = 100
W_FAIRNESS = 5

# Schedule representation:
# schedule[nurse][day] = 0 means OFF
# schedule[nurse][day] = 1 means Morning
# schedule[nurse][day] = 2 means Evening
# schedule[nurse][day] = 3 means Night


# -------------------- INITIALIZATION -------------------------

def random_schedule():
    """Generate a random schedule."""
    schedule = []

    for nurse in range(NURSES):
        row = []

        for day in range(DAYS):
            # 0 represents OFF
            row.append(random.randint(0, NUM_SHIFTS))

        schedule.append(row)

    return schedule


# -------------------- FITNESS FUNCTION -----------------------

def fitness(schedule, original=None, change_penalty=0):
    """
    Lower fitness is better.
    Mandatory constraint violations receive large penalties.
    """

    score = 0
    coverage = [[0] * NUM_SHIFTS for _ in range(DAYS)]
    weekly_load = [0] * NURSES

    for nurse in range(NURSES):
        for day in range(DAYS):
            shift = schedule[nurse][day]

            if shift == 0:
                continue

            # Availability constraint
            if not AVAILABILITY[nurse][day][shift - 1]:
                score += W_AVAILABILITY
                continue

            coverage[day][shift - 1] += 1
            weekly_load[nurse] += 1

    # Staffing coverage constraint
    for day in range(DAYS):
        for shift in range(NUM_SHIFTS):
            shortage = max(
                0, REQUIREMENTS[day][shift] - coverage[day][shift]
            )
            score += W_COVERAGE * shortage

    # Weekly workload limit
    for nurse in range(NURSES):
        excess = max(0, weekly_load[nurse] - MAX_WEEKLY_SHIFTS)
        score += W_WEEKLY_LIMIT * excess

    # Consecutive working days
    for nurse in range(NURSES):
        consecutive = 0

        for day in range(DAYS):
            if schedule[nurse][day] != 0:
                consecutive += 1

                if consecutive > MAX_CONSECUTIVE_DAYS:
                    score += W_CONSECUTIVE
            else:
                consecutive = 0

    # Minimum rest: prohibit Night followed by Morning
    for nurse in range(NURSES):
        for day in range(DAYS - 1):
            current = schedule[nurse][day]
            following = schedule[nurse][day + 1]

            if current == 3 and following == 1:
                score += W_REST

    # Workload fairness
    average_load = sum(weekly_load) / NURSES

    score += W_FAIRNESS * sum(
        (load - average_load) ** 2
        for load in weekly_load
    )

    # Rescheduling: penalize unnecessary changes
    if original is not None:
        changes = sum(
            schedule[n][d] != original[n][d]
            for n in range(NURSES)
            for d in range(DAYS)
        )
        score += change_penalty * changes

    return score


# -------------------- LEVY-INSPIRED SEARCH -------------------

def levy_step():
    """
    Heavy-tailed random step inspired by a Levy distribution.
    This is a simplified approximation, not an exact Mantegna
    Levy-flight implementation.
    """
    step = random.paretovariate(1.5) - 1.0

    if random.random() < 0.5:
        step = -step

    return step


def cuckoo_mutation(schedule):
    """Create a new candidate through discrete schedule changes."""
    new_schedule = deepcopy(schedule)

    # Heavy-tailed step influences the number of changes
    magnitude = abs(levy_step())
    changes = min(
        NURSES * DAYS,
        max(1, int(magnitude) + random.randint(1, 3))
    )

    for _ in range(changes):
        nurse = random.randrange(NURSES)
        day = random.randrange(DAYS)

        # OFF or one of the three shifts
        new_schedule[nurse][day] = random.randint(0, NUM_SHIFTS)

    return new_schedule


# -------------------- EVOLUTIONARY CROSSOVER -----------------

def crossover(parent1, parent2):
    """Combine two parent schedules."""
    child = deepcopy(parent1)

    for nurse in range(NURSES):
        for day in range(DAYS):
            if random.random() < 0.5:
                child[nurse][day] = parent2[nurse][day]

    return child


# -------------------- CONSTRAINT REPAIR ----------------------

def repair(schedule, attempts=100):
    """
    Greedily improve a schedule using single-assignment changes.
    Retain a change only if the fitness improves.
    """
    current = deepcopy(schedule)
    current_score = fitness(current)

    for _ in range(attempts):
        best_move = None
        best_score = current_score

        for _ in range(20):
            nurse = random.randrange(NURSES)
            day = random.randrange(DAYS)

            candidate = deepcopy(current)
            candidate[nurse][day] = random.randint(
                0, NUM_SHIFTS
            )

            candidate_score = fitness(candidate)

            if candidate_score < best_score:
                best_score = candidate_score
                best_move = candidate

        if best_move is None:
            break

        current = best_move
        current_score = best_score

        if current_score == 0:
            break

    return current


# -------------------- CUCKOO SEARCH --------------------------

def cuckoo_search():
    """Run the enhanced Cuckoo Search optimization."""

    population = [
        repair(random_schedule(), attempts=30)
        for _ in range(POPULATION_SIZE)
    ]

    population.sort(key=fitness)
    best = deepcopy(population[0])
    best_score = fitness(best)

    for iteration in range(MAX_ITERATIONS):

        # Generate and evaluate new cuckoo solutions
        for i in range(POPULATION_SIZE):
            candidate = cuckoo_mutation(population[i])
            candidate = repair(candidate, attempts=15)

            target = random.randrange(POPULATION_SIZE)

            if fitness(candidate) < fitness(population[target]):
                population[target] = candidate

        # Abandon a fraction of inferior nests
        number_abandoned = max(
            1,
            int(DISCOVERY_PROBABILITY * POPULATION_SIZE)
        )

        population.sort(key=fitness)

        for i in range(
            POPULATION_SIZE - number_abandoned,
            POPULATION_SIZE
        ):
            if random.random() < DISCOVERY_PROBABILITY:
                population[i] = repair(
                    random_schedule(), attempts=30
                )

        # Evolutionary crossover
        parent1 = random.choice(population[:max(
            1, POPULATION_SIZE // 2
        )])

        parent2 = random.choice(population)

        child = crossover(parent1, parent2)
        child = repair(child, attempts=15)

        worst_index = max(
            range(POPULATION_SIZE),
            key=lambda i: fitness(population[i])
        )

        if fitness(child) < fitness(population[worst_index]):
            population[worst_index] = child

        # Update best solution
        population.sort(key=fitness)

        if fitness(population[0]) < best_score:
            best = deepcopy(population[0])
            best_score = fitness(best)

        if (iteration + 1) % 50 == 0:
            print(
                f"Iteration {iteration + 1}: "
                f"Best fitness = {best_score}"
            )

        # Stop early if a zero-penalty solution is found
        if best_score == 0:
            break

    return best, best_score


# -------------------- DISPLAY SCHEDULE -----------------------

def display_schedule(schedule):
    print("\nNURSE SCHEDULE")
    print("-" * 65)

    print("Nurse".ljust(12), end="")

    for day in range(DAYS):
        print(f"Day {day + 1}".ljust(8), end="")

    print()

    for nurse in range(NURSES):
        print(f"Nurse {nurse + 1}".ljust(12), end="")

        for day in range(DAYS):
            shift = schedule[nurse][day]

            label = "OFF" if shift == 0 else SHIFTS[shift - 1]
            print(label[:7].ljust(8), end="")

        print()

    print("-" * 65)


# -------------------- RESCHEDULING ---------------------------

def reschedule_absent_nurse(schedule, absent_nurse, absent_day):
    """
    Mark a nurse absent for a given day and optimize the schedule.
    Nurse and day indices are zero-based.
    """
    global AVAILABILITY

    original = deepcopy(schedule)

    # Temporarily make the nurse unavailable for that day
    old_availability = deepcopy(AVAILABILITY[absent_nurse][absent_day])
    AVAILABILITY[absent_nurse][absent_day] = [False] * NUM_SHIFTS

    # Remove the absent nurse's assignment
    schedule[absent_nurse][absent_day] = 0

    population = [
        deepcopy(schedule)
        for _ in range(POPULATION_SIZE)
    ]

    best = deepcopy(schedule)
    best_score = fitness(
        best, original=original, change_penalty=10
    )

    for _ in range(100):
        for i in range(POPULATION_SIZE):
            candidate = cuckoo_mutation(population[i])
            candidate = repair(candidate, attempts=15)

            score = fitness(
                candidate, original=original, change_penalty=10
            )

            if score < best_score:
                best = deepcopy(candidate)
                best_score = score

            if fitness(candidate) < fitness(population[i]):
                population[i] = candidate

    AVAILABILITY[absent_nurse][absent_day] = old_availability

    return best, best_score


# -------------------- MAIN PROGRAM ---------------------------

if __name__ == "__main__":
    random.seed(42)

    best_schedule, best_fitness = cuckoo_search()

    print("\nBest fitness:", best_fitness)
    print("Feasible schedule:", best_fitness == 0)

    display_schedule(best_schedule)

    # Example rescheduling:
    # Nurse 1 becomes absent on Day 3.
    revised_schedule, revised_score = reschedule_absent_nurse(
        best_schedule,
        absent_nurse=0,
        absent_day=2
    )

    print("\nAfter rescheduling:")
    print("Fitness:", revised_score)
    display_schedule(revised_schedule)