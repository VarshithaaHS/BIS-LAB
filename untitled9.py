import random
import math
import matplotlib.pyplot as plt


# Calculate Euclidean distance between two cities
def distance(city1, city2):
    return math.sqrt(
        (city1[0] - city2[0]) ** 2 +
        (city1[1] - city2[1]) ** 2
    )


# Calculate total tour distance
def tour_length(tour, dist):
    total = 0

    for i in range(len(tour)):
        current_city = tour[i]
        next_city = tour[(i + 1) % len(tour)]
        total += dist[current_city][next_city]

    return total


# Calculate nearest neighbor tour length
def nearest_neighbor_length(dist):
    n = len(dist)
    unvisited = set(range(1, n))
    tour = [0]

    while unvisited:
        current = tour[-1]
        next_city = min(
            unvisited,
            key=lambda city: dist[current][city]
        )
        tour.append(next_city)
        unvisited.remove(next_city)

    return tour_length(tour, dist)


# Ant Colony System algorithm
def ant_colony_system(cities, ants, iterations):

    n = len(cities)

    # Create distance matrix
    dist = [
        [distance(cities[i], cities[j]) for j in range(n)]
        for i in range(n)
    ]

    beta = 2.0
    q0 = 0.9
    rho = 0.1
    phi = 0.1

    # Initial pheromone
    tau0 = 1.0 / (n * nearest_neighbor_length(dist))

    pheromone = [
        [tau0 for j in range(n)]
        for i in range(n)
    ]

    best_tour = None
    best_length = float('inf')

    history = []

    # Main iteration loop
    for iteration in range(iterations):

        iteration_best_tour = None
        iteration_best_length = float('inf')

        for ant in range(ants):

            # Random starting city
            start = random.randrange(n)

            tour = [start]
            unvisited = set(range(n))
            unvisited.remove(start)

            # Construct tour
            while unvisited:

                current = tour[-1]

                candidates = list(unvisited)

                # Calculate attractiveness
                values = {}

                for city in candidates:
                    heuristic = 1.0 / (dist[current][city] + 1e-10)

                    values[city] = (
                        pheromone[current][city] *
                        (heuristic ** beta)
                    )

                # ACS state transition rule
                if random.random() <= q0:

                    next_city = max(
                        candidates,
                        key=lambda city: values[city]
                    )

                else:

                    total = sum(values.values())

                    probabilities = [
                        values[city] / total
                        for city in candidates
                    ]

                    next_city = random.choices(
                        candidates,
                        weights=probabilities,
                        k=1
                    )[0]

                tour.append(next_city)
                unvisited.remove(next_city)

                # Local pheromone update
                pheromone[current][next_city] = (
                    (1 - phi) * pheromone[current][next_city]
                    + phi * tau0
                )

                pheromone[next_city][current] = (
                    (1 - phi) * pheromone[next_city][current]
                    + phi * tau0
                )

            # Calculate tour length
            length = tour_length(tour, dist)

            if length < iteration_best_length:
                iteration_best_length = length
                iteration_best_tour = tour[:]

            if length < best_length:
                best_length = length
                best_tour = tour[:]

        # Global pheromone evaporation
        for i in range(n):
            for j in range(n):
                pheromone[i][j] *= (1 - rho)

        # Global pheromone update on best tour
        for i in range(n):
            city1 = best_tour[i]
            city2 = best_tour[(i + 1) % n]

            pheromone[city1][city2] += rho / best_length
            pheromone[city2][city1] += rho / best_length

        history.append(best_length)

        print(
            "Iteration", iteration + 1,
            "- Best Distance:", round(best_length, 2)
        )

    return best_tour, best_length, history


# Display graphs
def plot_graph(cities, best_tour, history):

    # Graph 1: Best Route Graph
    route = best_tour + [best_tour[0]]

    x = [cities[i][0] for i in route]
    y = [cities[i][1] for i in route]

    plt.figure(figsize=(7, 5))
    plt.plot(x, y, marker='o', linestyle='-')

    for i, (cx, cy) in enumerate(cities):
        plt.text(cx, cy, "City " + str(i + 1))

    plt.title("ACO - Best TSP Route")
    plt.xlabel("X Coordinate")
    plt.ylabel("Y Coordinate")
    plt.grid(True)
    plt.show()

    # Graph 2: Convergence Graph
    plt.figure(figsize=(7, 5))

    plt.plot(
        range(1, len(history) + 1),
        history,
        marker='o'
    )

    plt.title("ACO Convergence Graph")
    plt.xlabel("Iteration")
    plt.ylabel("Best Distance")
    plt.grid(True)
    plt.show()


