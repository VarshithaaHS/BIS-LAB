import random

# Objective function: maximize
def fitness(x):
    return -(x - 5) ** 2 + 25

# Number of particles
n = 10

# Initial particles
particles = [random.uniform(-10, 10) for _ in range(n)]

# Personal best
pbest = particles.copy()

# Global best
gbest = max(pbest, key=fitness)

# PSO iterations
for i in range(50):

    for j in range(n):

        r1 = random.random()
        r2 = random.random()

        # Update particle position
        particles[j] = particles[j] + \
            r1 * (pbest[j] - particles[j]) + \
            r2 * (gbest - particles[j])

        # Update personal best
        if fitness(particles[j]) > fitness(pbest[j]):
            pbest[j] = particles[j]

    # Update global best
    best = max(pbest, key=fitness)

    if fitness(best) > fitness(gbest):
        gbest = best

print("Best Solution:", gbest)
print("Best Fitness:", fitness(gbest))