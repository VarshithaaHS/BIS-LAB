# ---------------------------------------
# 2. Multi-scale gradient calculation
# ---------------------------------------

def calculate_gradients(img):

    gray = cv2.cvtColor(
        (img * 255).astype(np.uint8),
        cv2.COLOR_RGB2GRAY
    ).astype(np.float32) / 255.0

    gradients = []

    for size in [3, 5, 7]:

        sigma = size / 3.0

        smooth = gaussian_filter(gray, sigma=sigma)

        gx = cv2.Sobel(
            smooth, cv2.CV_32F, 1, 0, ksize=3
        )

        gy = cv2.Sobel(
            smooth, cv2.CV_32F, 0, 1, ksize=3
        )

        magnitude = np.sqrt(gx**2 + gy**2)

        gradients.append(magnitude)

    return np.mean(gradients, axis=0)


# ---------------------------------------
# 3. Parallel Cellular Automata update
# ---------------------------------------

@njit(parallel=True)
def cellular_update(img, gradient, alpha, threshold):

    h, w, channels = img.shape

    updated = np.empty_like(img)

    for y in prange(h):

        for x in range(w):

            total = np.zeros(3)
            weight_sum = 0.0

            center_gradient = gradient[y, x]

            for dy in range(-1, 2):

                for dx in range(-1, 2):

                    ny = y + dy
                    nx = x + dx

                    if (ny < 0 or ny >= h or
                        nx < 0 or nx >= w):
                        continue

                    distance = 0.0

                    for c in range(3):
                        diff = img[y, x, c] - img[ny, nx, c]
                        distance += diff * diff

                    # Similarity between neighboring cells
                    color_weight = np.exp(
                        -distance / (2 * threshold * threshold + 1e-8)
                    )

                    gradient_weight = np.exp(
                        -abs(center_gradient - gradient[ny, nx]) * 5.0
                    )

                    weight = color_weight * gradient_weight

                    for c in range(3):
                        total[c] += weight * img[ny, nx, c]

                    weight_sum += weight

            for c in range(3):

                if weight_sum > 0:
                    average = total[c] / weight_sum
                else:
                    average = img[y, x, c]

                # Cellular state transition
                updated[y, x, c] = (
                    (1 - alpha) * img[y, x, c]
                    + alpha * average
                )

    return updated


# ---------------------------------------
# 4. Fitness evaluation
# ---------------------------------------

def fitness_function(params):

    alpha, threshold, iterations = params

    iterations = int(iterations)

    state = original.copy()

    gradient = calculate_gradients(original)

    for _ in range(iterations):

        state = cellular_update(
            state,
            gradient,
            alpha,
            threshold
        )

    # Reconstruction error
    reconstruction = np.mean((original - state) ** 2)

    # Smoothness measurement
    smoothness = (
        np.mean(np.abs(np.diff(state, axis=0)))
        + np.mean(np.abs(np.diff(state, axis=1)))
    )

    # Combined optimization objective
    fitness = reconstruction + 0.5 * smoothness

    return fitness


# ---------------------------------------
# 5. Evolutionary optimization
# ---------------------------------------

population_size = 8
generations = 5

# Each candidate: alpha, threshold, iterations
population = np.random.uniform(
    low=[0.1, 0.05, 2],
    high=[0.8, 0.3, 8],
    size=(population_size, 3)
)

best_fitness = float("inf")
best_params = None

for generation in range(generations):

    scores = []

    for candidate in population:

        score = fitness_function(candidate)
        scores.append(score)

        if score < best_fitness:

            best_fitness = score
            best_params = candidate.copy()

    # Select best candidates
    ranked = np.argsort(scores)

    population = population[ranked]

    # Generate new candidates through mutation
    new_population = [population[0].copy()]

    while len(new_population) < population_size:

        parent = population[
            np.random.randint(0, population_size // 2)
        ]

        child = parent + np.random.normal(
            0, [0.08, 0.025, 1], size=3
        )

        child[0] = np.clip(child[0], 0.1, 0.8)
        child[1] = np.clip(child[1], 0.05, 0.3)
        child[2] = np.clip(child[2], 2, 8)

        new_population.append(child)

    population = np.array(new_population)

    print(
        "Generation:", generation + 1,
        "Best Fitness:", round(best_fitness, 6)
    )


# ---------------------------------------
# 6. Final cellular automata execution
# ---------------------------------------

alpha, threshold, iterations = best_params

iterations = int(iterations)

segmented_state = original.copy()

gradient = calculate_gradients(original)

start_time = time.time()

for _ in range(iterations):

    segmented_state = cellular_update(
        segmented_state,
        gradient,
        alpha,
        threshold
    )

processing_time = time.time() - start_time


# ---------------------------------------
# 7. Image classification / segmentation
# ---------------------------------------

pixels = segmented_state.reshape(-1, 3)

kmeans = KMeans(
    n_clusters=5,
    random_state=42,
    n_init=10
)

labels = kmeans.fit_predict(pixels)

segmented_image = kmeans.cluster_centers_[labels]

segmented_image = segmented_image.reshape(
    original.shape
)


